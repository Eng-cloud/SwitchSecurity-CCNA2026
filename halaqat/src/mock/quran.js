export const SURAHS = SURAH_TABLE.map(([number, name, ayahCount, revelation, startPage]) => ({
  number,
  name,
  ayahCount,
  revelation,
  startPage,
  juz: Math.min(TOTAL_JUZ, Math.max(1, Math.ceil(startPage / 20.2))),
  hasText: Boolean(SURAH_TEXT[number]),
}));

const SURAH_BY_NUMBER = new Map(SURAHS.map((surah) => [surah.number, surah]));

export function getSurah(number) {
  return SURAH_BY_NUMBER.get(Number(number)) ?? null;
}

/**
 * يعيد آيات السورة. إن لم يكن النص متضمنًا تُعاد آيات بعلامة `unavailable`
 * لتعرض الواجهة إشعارًا واضحًا بدل نص مختلق.
 */
export function getSurahAyat(number) {
  const surah = getSurah(number);
  if (!surah) return [];
  const text = SURAH_TEXT[surah.number];
  if (text) {
    return text.map((content, index) => ({
      number: index + 1,
      text: content,
      unavailable: false,
    }));
  }
  return Array.from({ length: Math.min(surah.ayahCount, 20) }, (_, index) => ({
    number: index + 1,
    text: '',
    unavailable: true,
  }));
}

/** السور التي نصها متاح — تُستخدم في التسميع والاختبارات. */
export const SURAHS_WITH_TEXT = SURAHS.filter((surah) => surah.hasText);

export function searchSurahs(query) {
  const trimmed = (query ?? '').trim();
  if (!trimmed) return SURAHS;
  const asNumber = Number(trimmed);
  if (Number.isInteger(asNumber) && asNumber > 0) {
    return SURAHS.filter(
      (surah) => surah.number === asNumber || surah.startPage === asNumber,
    );
  }
  const normalized = trimmed.replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه');
  return SURAHS.filter((surah) =>
    surah.name.replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').includes(normalized),
  );
}

export function getJuzList() {
  return Array.from({ length: TOTAL_JUZ }, (_, index) => {
    const number = index + 1;
    const startPage = Math.round((number - 1) * 20.13) + 1;
    const firstSurah =
      SURAHS.filter((surah) => surah.startPage <= startPage).slice(-1)[0] ?? SURAHS[0];
    return { number, startPage, firstSurah: firstSurah.name };
  });
}

